import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import ts from 'typescript';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
const source=readFileSync(new URL('../app/question-text.tsx',import.meta.url),'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{jsx:ts.JsxEmit.ReactJSX,module:ts.ModuleKind.CommonJS}}).outputText;
const exports={};new Function('require','exports',compiled)(createRequire(import.meta.url),exports);
const render=text=>renderToStaticMarkup(React.createElement(exports.default,{text}));
const view=question=>renderToStaticMarkup(React.createElement(exports.QuestionView,{question}));
const strip=html=>html.replace(/<[^>]+>/g,'');

const html=render('阅读 `value`。\n\n```java\nint value = 1;\n  // 保留缩进\n```\n\n1. 解释输出\n2. 说明理由');
assert(html.includes('<pre'));
assert(html.includes('<span class="tok-c">// 保留缩进</span>'),'comment highlighted');
assert(html.includes(';\n  <span class="tok-c">'),'indentation before tokens survives highlighting');
assert(html.includes('<span class="tok-k">int</span>'),'java keyword highlighted');
assert(html.includes('data-lang="java"'),'known language sets the badge attribute');
assert(html.includes('<code>value</code>'));assert(html.includes('2. 说明理由'));assert(!html.includes('```'));
assert(strip(html).includes('int value = 1;\n  // 保留缩进'),'highlighting must not alter the visible text');
assert(render('{role: "tool",\n content: "result"}').includes('<pre'),'legacy trace uses code panel');
assert(!render('<script>alert(1)</script>').includes('<script>'),'generated HTML stays escaped');
assert(render('```text\n<svg onload=alert(1)>\n```').includes('&lt;svg'));
const injected=render('```java\nString s = "<img src=x onerror=alert(1)>";\n```');
assert(!injected.includes('<img')&&injected.includes('&lt;img'),'highlighted code stays escaped');
const json=render('```json\n{"count": 1, "ok": true}\n```');
assert(json.includes('<span class="tok-t">&quot;count&quot;</span>')&&json.includes('<span class="tok-n">1</span>')&&json.includes('<span class="tok-k">true</span>'),'json keys, numbers and literals highlighted');
const python=render('```python\ndef f():\n    return 42  # 答案\n```');
assert(python.includes('<span class="tok-k">def</span>')&&python.includes('\n    <span class="tok-k">return</span>')&&python.includes('<span class="tok-n">42</span>')&&python.includes('<span class="tok-c"># 答案</span>'),'python highlight keeps four-space indentation');
const plain=render('```text\nint value = 1;\n```');
assert(!plain.includes('tok-')&&!plain.includes('data-lang'),'text fence renders without highlight or badge');
const unclosed=render('```java\nint x = 1;');
assert(unclosed.includes('<pre')&&unclosed.includes('<span class="tok-k">int</span>'),'unclosed fence still renders highlighted code');

const structured=view({prompt:'输出结果是什么？',material:'阅读以下代码：\n\n```java\nint a = 1;\n```',requirements:'不超过 200 字'});
assert(structured.includes('question-section'),'structured question uses sections');
const labels=['材料','题干','作答要求'].map(label=>structured.indexOf(label));
assert(labels.every(index=>index>=0)&&labels[0]<labels[1]&&labels[1]<labels[2],'材料/题干/作答要求 render in order');
assert(structured.includes('<span class="tok-k">int</span>'),'material code is highlighted');
const legacy=view({prompt:'旧题目\n\n```java\nint a = 1;\n```'});
assert(!legacy.includes('question-section-label'),'legacy single-blob question keeps original rendering');
assert(legacy.includes('<span class="tok-k">int</span>'),'legacy question still gets code highlighting');
const partial=view({prompt:'只有要求的题？',requirements:'先列提纲'});
assert(partial.includes('题干')&&partial.includes('作答要求')&&!partial.includes('>材料<'),'requirements-only question has no material section');
console.log('PASS: paragraph/newline/indent preservation, fenced and legacy trace code, inline code, HTML escaping, token highlighting, and structured material/stem/requirements sections.');
